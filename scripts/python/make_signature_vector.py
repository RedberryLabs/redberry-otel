"""Write test/vectors/signature.json with VALP's own Python code (valp_core.keys / valp_core.hashing).

The TypeScript tests check that @redberrylabs/otel derives the same key_id, produces the same signature
(Ed25519 is deterministic) and that VALP's verifier accepts it. Run with a VALP checkout on the path:

    PYTHONPATH=<VALP>/src <VALP>/.venv/bin/python scripts/python/make_signature_vector.py
"""

from __future__ import annotations

import base64
import hashlib
import json
import pathlib

from cryptography.hazmat.primitives.serialization import Encoding, NoEncryption, PrivateFormat

from valp_core import hashing, keys

try:  # the hashes route's own signature decoder (VALP PR #53); optional on older checkouts
    from valp_collector.projects import decode_signature
except ImportError:  # pragma: no cover
    decode_signature = None

OUT = pathlib.Path(__file__).resolve().parents[2] / "test" / "vectors" / "signature.json"
SEED = hashlib.sha256(b"@redberry/otel signature vector 1").digest()

key = keys.SigningKey.from_seed(SEED)
pkcs8 = key._sk.private_bytes(Encoding.DER, PrivateFormat.PKCS8, NoEncryption())  # what the CLI emits
body = {
    "v": 1,
    "agent_id": "AGT-01K5V8QJ3M7XW2ZB4YRNCDEFGH",
    "trace_id": "45e3cc173b7aae7a6e658021710f8848",
    "sha256": hashlib.sha256(b"stored bytes").hexdigest(),
    "size": 5321,
    "started_at": "2026-10-21T10:14:18.004Z",
    "ended_at": "2026-10-21T10:14:27.744Z",
    "stored": True,
    "store": "vercel-blob",
    "leaf_kind": "stored-bytes",
}
raw = json.dumps(body, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()
signature = key.sign_digest(hashlib.sha256(raw).digest())
sig_b64 = base64.b64encode(signature).decode()
assert keys.verify(key.public_key, hashlib.sha256(raw).digest(), signature)
if decode_signature is not None:
    assert decode_signature(sig_b64) == signature

vector = {
    "comment": "Generated by scripts/python/make_signature_vector.py with VALP valp_core; do not edit.",
    "signing_key_pkcs8_b64": base64.b64encode(pkcs8).decode(),
    "seed_hex": SEED.hex(),
    "public_key_hex": key.public_key.hex(),
    "key_id": hashing.key_id(key.public_key),
    "body": raw.decode(),
    "body_sha256_hex": hashlib.sha256(raw).hexdigest(),
    "signing_message_hex": hashing.signing_message(hashlib.sha256(raw).digest()).hex(),
    "signature_b64": sig_b64,
    "signature_header": "ed25519=" + sig_b64,
}
OUT.write_text(json.dumps(vector, indent=2) + "\n")
print(f"wrote {OUT}: key_id {vector['key_id']}")
